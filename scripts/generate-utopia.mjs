/**
 * Regenerates src/styles/tokens/utopia.css — the fluid type and space scales.
 *
 * Formula and rounding follow utopia.fyi (utopia-core): every step interpolates
 * linearly between a size at MIN_VIEWPORT and a size at MAX_VIEWPORT and is
 * expressed as clamp(min, intercept + slope·vi, max) in rem.
 *
 *   Type  — https://utopia.fyi/type/calculator/
 *           360px: 16px base, ratio 1.125 (Major Second)
 *           1440px: 16px base, ratio 1.2 (Minor Third)
 *           Steps 0 → 8. Body stays 16px at every width (brand: Body 16/16px);
 *           headings grow towards the brand's desktop sizes.
 *
 *   Space — https://utopia.fyi/space/calculator/
 *           16px base at both ends, so every single step lands on the brand's
 *           4px grid (4, 8, 12, 16, 24, 32, 48, 64, 96, 128). Fluidity comes
 *           from the one-up and custom pairs, e.g. --space-xl-3xl = 48 → 96px,
 *           which reproduces the brand's section padding (48 mobile → 96 desktop).
 *
 * Run: npm run tokens:utopia
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MIN_VIEWPORT = 360;
const MAX_VIEWPORT = 1440;

const TYPE = { minBase: 16, minRatio: 1.125, maxBase: 16, maxRatio: 1.2, steps: [0, 1, 2, 3, 4, 5, 6, 7, 8] };

const SPACE = {
  minBase: 16,
  maxBase: 16,
  sizes: { '3xs': 0.25, '2xs': 0.5, xs: 0.75, s: 1, m: 1.5, l: 2, xl: 3, '2xl': 4, '3xl': 6, '4xl': 8 },
  customPairs: [['s', 'l'], ['m', 'xl'], ['l', '2xl'], ['xl', '3xl'], ['2xl', '4xl']],
};

const round = (n) => Math.round((n + Number.EPSILON) * 10000) / 10000;

function clamp(minPx, maxPx) {
  const [lo, hi] = minPx > maxPx ? [maxPx, minPx] : [minPx, maxPx];
  const slope = (maxPx / 16 - minPx / 16) / (MAX_VIEWPORT / 16 - MIN_VIEWPORT / 16);
  const intercept = (-MIN_VIEWPORT / 16) * slope + minPx / 16;
  if (round(slope) === 0) return `${round(minPx / 16)}rem`;
  return `clamp(${round(lo / 16)}rem, ${round(intercept)}rem + ${round(slope * 100)}vi, ${round(hi / 16)}rem)`;
}

const lines = [];
lines.push('/* GENERATED by scripts/generate-utopia.mjs — do not edit by hand. */');
lines.push(`/* Utopia fluid scales, ${MIN_VIEWPORT}px → ${MAX_VIEWPORT}px. See DESIGN_TOKENS.md. */`);
lines.push(':root {');
lines.push(`  /* Type: ${TYPE.minBase}px × ${TYPE.minRatio} @${MIN_VIEWPORT} → ${TYPE.maxBase}px × ${TYPE.maxRatio} @${MAX_VIEWPORT} */`);
for (const step of TYPE.steps) {
  const min = TYPE.minBase * TYPE.minRatio ** step;
  const max = TYPE.maxBase * TYPE.maxRatio ** step;
  lines.push(`  --step-${step}: ${clamp(min, max)}; /* ${round(min)}px → ${round(max)}px */`);
}
lines.push('');
lines.push(`  /* Space: ${SPACE.minBase}px @${MIN_VIEWPORT} → ${SPACE.maxBase}px @${MAX_VIEWPORT} */`);
const names = Object.keys(SPACE.sizes);
const px = (name, base) => SPACE.sizes[name] * base;
for (const name of names) {
  lines.push(`  --space-${name}: ${clamp(px(name, SPACE.minBase), px(name, SPACE.maxBase))}; /* ${px(name, SPACE.minBase)}px → ${px(name, SPACE.maxBase)}px */`);
}
lines.push('');
lines.push('  /* One-up pairs */');
for (let i = 0; i < names.length - 1; i++) {
  const [a, b] = [names[i], names[i + 1]];
  lines.push(`  --space-${a}-${b}: ${clamp(px(a, SPACE.minBase), px(b, SPACE.maxBase))}; /* ${px(a, SPACE.minBase)}px → ${px(b, SPACE.maxBase)}px */`);
}
lines.push('');
lines.push('  /* Custom pairs */');
for (const [a, b] of SPACE.customPairs) {
  lines.push(`  --space-${a}-${b}: ${clamp(px(a, SPACE.minBase), px(b, SPACE.maxBase))}; /* ${px(a, SPACE.minBase)}px → ${px(b, SPACE.maxBase)}px */`);
}
lines.push('}');

const out = fileURLToPath(new URL('../src/styles/tokens/utopia.css', import.meta.url));
writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${out}`);
